# devices/omni_m151/parser.py
# ─────────────────────────────────────────────────────────────────────────────
# Command handlers for OMNI M151 scooter protocol.
#
# Each handle_* function processes one incoming command type.
# They all receive:
#   conn (socket): The scooter's TCP connection - for sending responses back.
#   msg  (dict):   Parsed message from core/packet_parser.py
#                  Keys: "imei", "command", "data"
#
# Handlers that need to send commands back use build_command() from commands.py.
# Handlers that need to forward data to Laravel use requests.post().
# Handlers that need shared state (locks, pending results) import from server.py
# during this transition phase - will be moved to connection_pool.py in Step 5.
# ─────────────────────────────────────────────────────────────────────────────

import os
import requests

from devices.omni_m151.commands import build_command


def handle_Q0(conn, msg):
    """
    Handle Q0 - Check-in command.

    Sent by scooter immediately after connecting (and after every reconnect).
    Contains: voltage (×100), battery %, signal strength.
    Protocol: server does NOT respond to Q0.

    Args:
        conn (socket): Scooter's TCP connection.
        msg  (dict):   Parsed Q0 message.
                       data[0] = voltage × 100 (412 = 4.12V)
                       data[1] = battery %
                       data[2] = signal strength (2–32)
    """
    data    = msg["data"]
    voltage = int(data[0]) / 100  
    battery = data[1]
    signal  = data[2]
    print(f"  [Q0] CHECK-IN | voltage={voltage}V | battery={battery}% | signal={signal}")


def handle_H0(conn, msg):
    """
    Handle H0 - Heartbeat command.

    Sent every ~4 minutes to say "I'm still alive".
    We forward battery level to Laravel so admin panel shows fresh data.
    Server does NOT respond to H0 over TCP.

    H0 data fields:
        data[0] = vehicle status (0=unlocked, 1=locked)
        data[1] = IoT voltage × 100 (412 = 4.12V)
        data[2] = signal strength (2–32)
        data[3] = battery level % (0–100)
        data[4] = charging status (0=not charging, 1=charging)

    Args:
        conn (socket): Scooter's TCP connection (not used - no TCP response).
        msg  (dict):   Parsed H0 message.
    """
    # Import here to avoid circular imports during transition.
    # After Step 5, these come from core/connection_pool.py.
    import server as _server

    data     = msg["data"]
    status   = "unlocked" if data[0] == "0" else "locked"
    battery  = int(data[3]) 
    charging = "charging" if data[4] == "1" else "not charging"

    print(f"  [H0] HEARTBEAT | status={status} | battery={battery}% | {charging}")

    # Forward battery to Laravel - admin panel reads this to show live battery %
    try:
        requests.post(
            f"{_server.LARAVEL_URL}/api/internal/heartbeat",
            json={
                "imei":    msg["imei"],
                "battery": battery,
            },
            headers={
                # X-Internal-Secret proves this call came from our TCP server, not the internet
                "X-Internal-Secret": os.environ.get(
                    "TCP_SERVER_SECRET", _server.INTERNAL_SECRET
                )
            },
            timeout=3,
        )
    except Exception as e:
        # Log and continue - a failed heartbeat must NEVER crash the TCP server
        print(f"  [H0] Failed to forward heartbeat to Laravel: {e}")


def handle_R0(conn, msg, imei):
    """
    Handle R0 - Key exchange response.

    After we send R0 to request a lock/unlock, the scooter replies with a
    random KEY. We must use this KEY in the following L0 (unlock) or L1 (lock).

    This is the middle step of the 3-step handshake:
      Step 1: server sends R0 (request key)
      Step 2: scooter replies R0 with KEY  ← this handler
      Step 3: server sends L0/L1 with KEY

    R0 data fields:
        data[0] = operation (0=unlock, 1=lock)
        data[1] = KEY generated by scooter (0–255)
        data[2] = user ID echoed back
        data[3] = timestamp echoed back

    Args:
        conn (socket): Scooter's TCP connection - we send L0 or L1 here.
        msg  (dict):   Parsed R0 message.
        imei (str):    Scooter IMEI (needed to build the L0/L1 command).
    """
    import server as _server

    data      = msg["data"]
    operation = "unlock" if data[0] == "0" else "lock"
    key       = data[1]
    user_id   = data[2]
    timestamp = data[3]
    print(f"  [R0] KEY RECEIVED | operation={operation} | KEY={key} | user={user_id}")

    if data[0] == "0":
        # Unlock: send L0 with the KEY the scooter just gave us
        conn.sendall(build_command(imei, "L0", key, user_id, timestamp))
        print(f"  [L0] UNLOCK COMMAND SENT | KEY={key}")
    else:
        # Lock: send L1 with the KEY
        conn.sendall(build_command(imei, "L1", key))
        print(f"  [L1] LOCK COMMAND SENT | KEY={key}")

        # If this lock was triggered by a geofence violation, clear the flag
        # so execute_geofence_sequence() knows the lock is done
        with _server.connections_lock:
            _server.pending_geofence_locks.pop(imei, None)


def handle_L0(conn, msg, imei):
    """
    Handle L0 - Unlock result from scooter.

    Scooter reports whether the unlock succeeded or failed.
    Protocol requires server to send an L0 acknowledgment back.

    L0 data fields:
        data[0] = status (0=success, 1=failure, 2=key error)

    Args:
        conn (socket): Scooter's TCP connection - we send the ack here.
        msg  (dict):   Parsed L0 message.
        imei (str):    Scooter IMEI (needed to build the ack command).
    """
    status_codes = {"0": "SUCCESS", "1": "FAILURE", "2": "KEY ERROR"}
    status = status_codes.get(msg["data"][0], "UNKNOWN")
    print(f"  [L0] UNLOCK RESULT: {status}")

    # Send bare L0 acknowledgment - no params, just confirms receipt
    conn.sendall(build_command(imei, "L0"))
    print(f"  [L0] ACK SENT")


def handle_L1(conn, msg, imei):
    """
    Handle L1 - Lock result from scooter.

    Scooter reports lock outcome and the ride duration.
    If lock_scooter() is waiting (blocked on threading.Event), we unblock it here.

    L1 data fields:
        data[0] = status (0=success, 1=failure, 2=key error, 3=still riding)
        data[3] = ride duration in minutes (reported by device hardware)

    Args:
        conn (socket): Scooter's TCP connection - we send the ack here.
        msg  (dict):   Parsed L1 message.
        imei (str):    Scooter IMEI - key into pending_lock_results.
    """
    import server as _server

    status_codes = {
        "0": "SUCCESS",
        "1": "FAILURE",
        "2": "KEY ERROR",
        "3": "RIDING - CANNOT LOCK",
    }
    status   = status_codes.get(msg["data"][0], "UNKNOWN")
    duration = int(msg["data"][3]) if len(msg["data"]) > 3 else 0
    success  = msg["data"][0] == "0"

    print(f"  [L1] LOCK RESULT: {status} | ride duration={duration} min")

    # Protocol requires acknowledgment - scooter expects this to finish the sequence
    conn.sendall(build_command(imei, "L1"))

    # If lock_scooter() is blocking on event.wait(), unblock it now.
    # We write the result first, then call event.set() - order matters.
    # If we set() before writing, lock_scooter() might read before we write.
    with _server.pending_lock_results_lock:
        if imei in _server.pending_lock_results:
            _server.pending_lock_results[imei]["duration"] = duration
            _server.pending_lock_results[imei]["success"]  = success
            _server.pending_lock_results[imei]["event"].set()


def handle_D0(conn, msg):
    """
    Handle D0 - GPS location packet.

    Received in two cases:
      - Response to our one-time D0 ping request
      - Automatic update while D1 real-time tracking is active

    Coordinates arrive in NMEA DDMM.MMMM format - we convert to decimal degrees
    before forwarding to Laravel, which runs the geofence check.

    Conversion formula:
        DDMM.MMMM → DD + MM.MMMM / 60
        Example: "4159.8140" → 41 + 59.8140/60 = 41.9969°

    D0 data fields (after command code):
        data[0] = ? (unused)
        data[1] = time (HHMMSS.SS)
        data[2] = fix validity ('A'=valid, 'V'=no fix)
        data[3] = latitude in DDMM.MMMM format
        data[4] = N/S indicator
        data[5] = longitude in DDDMM.MMMM format
        data[6] = E/W indicator

    Args:
        conn (socket): Scooter's TCP connection (not used - no TCP response).
        msg  (dict):   Parsed D0 message.
    """
    import server as _server

    data = msg["data"]
    imei = msg["imei"]

    # data[2] = 'A' means valid GPS fix; 'V' means no satellite lock yet
    # We must not forward 'V' coordinates - they're 0,0 or last known, not current
    if len(data) < 7 or data[2] == "V":
        print(f"  [D0] GPS: no fix yet")
        return

    # Convert latitude: DDMM.MMMM → decimal degrees
    # "4159.4600" → DD=41, MM=59.4600 → 41 + 59.46/60 = 41.991°
    raw_lat = data[3]
    lat = float(raw_lat[:2]) + float(raw_lat[2:]) / 60

    # South latitudes are negative (Georgia is N, so this won't trigger normally)
    if data[4] == "S":
        lat = -lat

    # Convert longitude: DDDMM.MMMM → decimal degrees
    # "04145.9000" → DDD=041, MM=45.9000 → 41 + 45.90/60 = 41.765°
    raw_lng = data[5]
    lng = float(raw_lng[:3]) + float(raw_lng[3:]) / 60

    # West longitudes are negative (Georgia is E, so this won't trigger normally)
    if data[6] == "W":
        lng = -lng

    print(f"  [D0] GPS: lat={lat:.6f}, lng={lng:.6f}")

    # Forward to Laravel - Laravel checks if point is inside the operating zone
    # If outside, Laravel calls back /geofence-violation on our HTTP server
    try:
        requests.post(
            f"{_server.LARAVEL_URL}/api/internal/gps-update",
            json={"imei": imei, "lat": lat, "lng": lng},
            headers={
                "X-Internal-Secret": os.environ.get(
                    "TCP_SERVER_SECRET", _server.INTERNAL_SECRET
                )
            },
            timeout=3,
        )
    except Exception as e:
        print(f"  [D0] Failed to forward GPS to Laravel: {e}")


def handle_S6(conn, msg):
    """
    Handle S6 - Vehicle status report.

    Sent in response to our S6 data request. Contains battery, speed, lock status.
    No TCP response needed.

    S6 data fields:
        data[0] = battery %
        data[2] = current speed km/h
        data[6] = lock status (0=unlocked, 1=locked)

    Args:
        conn (socket): Scooter's TCP connection (not used).
        msg  (dict):   Parsed S6 message.
    """
    data = msg["data"]
    print(
        f"  [S6] VEHICLE DATA | battery={data[0]}% | "
        f"speed={data[2]}km/h | "
        f"status={'unlocked' if data[6] == '0' else 'locked'}"
    )


def handle_W0(conn, msg, imei):
    """
    Handle W0 - Alarm event.

    Scooter sends W0 on: unauthorized movement, tip-over, disassembly, low battery.
    Protocol requires server to send W0 acknowledgment - otherwise scooter repeats.

    W0 data fields:
        data[0] = alarm type code
            "1" = unauthorized movement
            "2" = tip-over
            "3" = unauthorized disassembly
            "4" = low battery
            "6" = tip-over cleared
            "7" = disassembly alarm cleared

    Args:
        conn (socket): Scooter's TCP connection - we send the ack here.
        msg  (dict):   Parsed W0 message.
        imei (str):    Scooter IMEI (needed to build the ack command).
    """
    alarm_types = {
        "1": "unauthorized movement",
        "2": "tip-over",
        "3": "unauthorized disassembly",
        "4": "low battery",
        "6": "tip-over cleared",
        "7": "disassembly alarm cleared",
    }
    alarm = alarm_types.get(msg["data"][0], "unknown")
    print(f"  [W0] ALARM: {alarm}")

    # Must always acknowledge - scooter repeats the alarm until it gets W0 back
    conn.sendall(build_command(imei, "W0"))